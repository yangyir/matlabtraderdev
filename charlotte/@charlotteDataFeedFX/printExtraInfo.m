function [] = printExtraInfo(obj,extrainfo,freq)
    % a charlotteDataFeedFX static method
    if strcmpi(freq,'m15')
        dtshift = 1/96;
    elseif strcmpi(freq,'m30')
        dtshift = 1/48;
    elseif strcmpi(freq,'h1')
        dtshift = 1/24;
    elseif strcmpi(freq,'h4')
        dtshift = 1/4;
    end
    for i = 1:size(obj.codes_,1)
        if i == 1
            fprintf('%10s%10s%10s%14s%10s%10s%8s%8s%10s%10s%10s%10s%10s%10s%10s\n',...
                'Code','Freq','Last','Time','HH','LL','BS','SS','LevelUp','LevelDn','Jaw','Teeth','Lips','ATR','AO');
        end
        
        if strcmpi(obj.codes_{i},'USDJPY')
            dataformat = '%10s%10s%10.3f%14s%10.3f%10.3f%8d%8d%10.3f%10.3f%10.3f%10.3f%10.3f%10.3f%10.3f\n';
        elseif strcmpi(obj.codes_{i},'XAUUSD')
            dataformat = '%10s%10s%10.2f%14s%10.2f%10.2f%8d%8d%10.2f%10.2f%10.2f%10.2f%10.2f%10.2f%10.2f\n';
        else
            dataformat = '%10s%10s%10.5f%14s%10.5f%10.5f%8d%8d%10.5f%10.5f%10.5f%10.5f%10.5f%10.5f%10.5f\n';
        end
        
        fprintf(dataformat,obj.codes_{i},...
            upper(freq),...
            extrainfo{i}.px(end,5),...
            datestr(extrainfo{i}.px(end,1)+dtshift,'dd-mmm HH:MM'),...
            extrainfo{i}.hh(end),...
            extrainfo{i}.ll(end),...
            extrainfo{i}.bs(end),...
            extrainfo{i}.ss(end),...
            extrainfo{i}.lvlup(end),...
            extrainfo{i}.lvldn(end),...
            extrainfo{i}.jaw(end),...
            extrainfo{i}.teeth(end),...
            extrainfo{i}.lips(end),...
            extrainfo{i}.atr(end),...
            extrainfo{i}.ao(end));
    end
    fprintf('\n');
end